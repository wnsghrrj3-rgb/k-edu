// 211차 물음 끝맺음 — 원문 「~다.」「~는가?」「~면?」을 학생 말씨(요)로. 순서 중요(구체 → 일반).
function qfix(q) {
  const BODY = [[/용량표다\. /g, '용량표예요. '], [/요금표다\. /g, '요금표예요. '], [/들이다\. /g, '들이예요. '], [/무게다\. /g, '무게예요. '],
    [/포장한다\. /g, '포장해요. '], [/준다\. /g, '줘요. '], [/판다\. /g, '팔아요. '], [/셈했다\. /g, '셈했어요. '], [/원이다\. /g, '원이에요. '], [/\*\*이다\. /g, '**이에요. '], [/찾았다\. /g, '찾았어요. ']];
  BODY.forEach(([a, b]) => { q = q.replace(a, b); });
  return q.replace(/친구가 본다면\?$/, '친구가 볼 수 있을까요?').replace(/고르면\?$/, '고르면 무엇일까요?')
    .replace(/해야 하는가\?$/, '해야 할까요?').replace(/어야 하는가\?$/, '어야 할까요?').replace(/야 하는가\?$/, '야 할까요?')
    .replace(/받는가\?$/, '받을까요?').replace(/수 있는가\?$/, '수 있을까요?').replace(/했는가\?/, '했을까요?')
    .replace(/친구는\?/, '친구는 누구일까요?')
    .replace(/인가\?$/, '일까요?').replace(/는\?$/, '는 무엇일까요?').replace(/면\?$/, '면 얼마일까요?').replace(/은\?$/, '은 무엇일까요?');
}

