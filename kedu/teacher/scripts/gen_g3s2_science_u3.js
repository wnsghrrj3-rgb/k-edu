function srcContent(sl, lead, fig) {
  if (sl.kind === 'feat') return lead;
  if (sl.kind === 'classify') { const crit = sl.crits.find(c => c.t === fig.q); return nm(sl.msgs[crit.id]); }
  return sl.text || '';
}
/* 원문 문항 → 기본 문제 */
function problemData(q, title, body, icon) {
  const d = { title, scenario: { icon: icon || '🔬', body: [body, q.body].filter(Boolean).join('\n') }, question: q.t };
  if (q.kind === 'mcq') { d.options = q.opts.map((t, i) => (i === q.ci ? { text: t, correct: true } : { text: t })); d.note = '풀이: ' + q.hints[1] + ' → **' + nm(q.opts[q.ci]) + '**'; }
  else if (q.kind === 'ms') { d.options = q.chips.map(c => (c.hit ? { text: c.t, correct: true } : { text: c.t })); d.multi = true; d.note = '풀이: ' + q.hints[1] + ' → 알맞은 것 **' + q.chips.filter(c => c.hit).length + '개**'; }
  else if (q.kind === 'cls') { d.scenario.body += '\n나눌 것: ' + q.items.map(it => it.emoji + ' ' + it.t).join(' · ') + '\n통: ' + q.bins.map(b => b.name).join(' · '); d.answer = q.bins.map(b => b.name + ' — ' + q.items.filter(it => it.bin === b.id).map(it => it.t).join(' · ')).join(' / '); d.note = '풀이: ' + q.hints[1]; }
  else if (q.kind === 'mt') { d.scenario.body += '\n왼쪽: ' + q.pairs.map(p => p[0].replace(/\n/g, ' ')).join(' · ') + '\n오른쪽: ' + q.pairs.map(p => p[1]).join(' · '); d.answer = q.pairs.map(p => p[0].replace(/\n/g, ' ') + ' ↔ ' + p[1]).join(' / '); d.note = '풀이: ' + q.hints[1]; }
  return d;
}

