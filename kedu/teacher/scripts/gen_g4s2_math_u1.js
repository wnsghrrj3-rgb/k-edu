function problemData(p, title, body, fig) {
  const d = { title, scenario: { icon: '🍎', body }, question: p.q.replace(/인가요\?$/, '일까요?') };
  if (fig) d.fig = fig;
  if (p.opts) { d.options = p.opts.map((t, i) => (i === p.ci ? { text: t, correct: true } : { text: t })); d.note = '풀이: ' + p.hints.join(' ') + ' → **' + p.opts[p.ci] + '**'; }
  else { d.input = 'count_input'; d.answer = +p.a; d.note = '풀이: ' + p.hints.join(' ') + ' → **' + p.a + '**'; }
  return d;
}

