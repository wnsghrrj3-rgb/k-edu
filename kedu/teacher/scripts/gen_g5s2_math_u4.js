const TYPE = { video: ['video', '🎥', ['concept', 'motivate']], q: ['fun_question', '💡', ['concept', 'basic_problem']], tip: ['tip', '🧩', ['concept', 'misconception']], real: ['real_world', '🌍', ['real_world', 'summary']], game: ['game', '🎮', ['leveled_problem', 'offline_activity']], x: ['misconception', '⚠️', ['misconception', 'basic_problem']], e: ['example', '📝', ['concept', 'offline_activity']], c: ['checklist', '✅', ['next_lesson']] };
const PFX = { video: 'v', q: 'q', tip: 't', real: 'r', game: 'g', x: 'x', e: 'e', c: 'c' };
function extras(n, list) {
  const cnt = {};
  return list.map(line => {
    const p = line.split('|'); const k = p[0]; cnt[k] = (cnt[k] || 0) + 1; const [type, icon, fit] = TYPE[k];
    const id = PFX[k] + '_l' + n + '_' + cnt[k];
    if (k === 'video') return { id, type, icon, title: p[1], url: 'https://www.youtube.com/results?search_query=' + encodeURIComponent(p[2]).replace(/%20/g, '+'), description: p[3], source: '유튜브 검색 (교사 사전 확인 권장)', fit_slides: fit };
    return { id, type, icon, title: p[1], content: p[2], fit_slides: fit };
  });
}
// 217차 「결」 낱말 거르기 — 원문 「결과」「해결」을 화면에 두지 않는다 · 219차 「계산 결과 」 → 「계산한 값 」 · 표 제목 인물 → 「우리 반」
const nk = (s) => String(s).replace(/민주네 반/g, '우리 반').replace(/계산 결과 /g, '계산한 값 ').replace(/계산 결과가/g, '계산한 값이').replace(/결과가/g, '값이').replace(/결과는/g, '값은').replace(/결과를/g, '값을').replace(/어떻게 해결했나/g, '어떻게 풀었나').replace(/해결/g, '풀이');
const lines = (t) => String(t).replace(/([다요])\. /g, '$1.\n').trim();
const clone = (o) => JSON.parse(nk(JSON.stringify(o)));

// 219차 물음 끝맺음 — 원문 「~다.」「~인가?」「~면?」「~은?」을 학생 말씨(요)로. 순서 중요(구체 → 일반).
function qfix(q) {
  const BODY = [[/계산한다\. /g, '계산해요. '], [/ 이다\. /g, ' 이에요. '], [/나타냈다\. /g, '나타냈어요. ']];
  BODY.forEach(([a, b]) => { q = q.replace(a, b); });
  return q.replace(/큰가, 작은가\?$/, '클까요, 작을까요?').replace(/하는가\?$/, '할까요?').replace(/인가\?$/, '일까요?').replace(/계산하면\?$/, '계산하면 얼마일까요?')
    .replace(/값은\?$/, '값은 얼마일까요?').replace(/것은\?$/, '것은 무엇일까요?').replace(/식은\?$/, '식은 무엇일까요?').replace(/는\?$/, '는 얼마일까요?');
}

