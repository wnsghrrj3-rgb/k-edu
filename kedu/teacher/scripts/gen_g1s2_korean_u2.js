const TYPE = { video: ['video', '🎥', ['concept', 'motivate']], q: ['fun_question', '💡', ['concept', 'basic_problem']], tip: ['tip', '🧩', ['concept', 'misconception']], real: ['real_world', '🌍', ['real_world', 'summary']], game: ['game', '🎮', ['leveled_problem', 'offline_activity']], x: ['misconception', '⚠️', ['misconception', 'basic_problem']], e: ['example', '📝', ['concept', 'offline_activity']], c: ['checklist', '✅', ['next_lesson']] };
const PFX = { video: 'v', q: 'q', tip: 't', real: 'r', game: 'g', x: 'x', e: 'e', c: 'c' };
function extras(n, list) {
  const cnt = {};
  return list.map(line => {
    const p = line.split('|'); const k = p[0]; cnt[k] = (cnt[k] || 0) + 1; const [type, icon, fit] = TYPE[k];
    const id = PFX[k] + '_l' + n + '_' + cnt[k];
    if (k === 'video') return { id, type, icon, title: p[1], url: 'https://www.youtube.com/results?search_query=' + encodeURIComponent(p[2]).replace(/%20/g, '+'), description: p[3], source: '유튜브 검색 (교사 사전 확인 권장)', fit_slides: fit };
    return { id, type, icon, title: p[1], content: p[2], fit_slides: fit };
  });
}
/* 원문 장 → 개념 말풍선 글 (글 판 장·글 없는 장은 교사 한 줄(lead), 나머지는 원문 그대로 — 게이트 F 가 같은 규칙으로 되짚는다) */
function srcContent(sl) {
  if (sl.kind === 'recap') return sl.items.join('\n');
  if (sl.kind === 'stage') return [sl.text, sl.stage].filter(Boolean).join('\n');
  if (!sl.text && sl.extra) return sl.extra.join('\n');
  return sl.text || '';
}
/* 가려내기 문항 → 기본 문제 */
/* 126차: 원문 힌트가 없는 문항은 T 표의 풀이 한 줄(h)을 쓰고, 원문 힌트의 「힌트:」 머리는 뗀다 */
function problemData(sl, title, body, icon, keep, h) {
  const d = { title, scenario: { icon: icon || '📖', body }, question: sl.t };
  const hint = String(sl.hint || h || '그림과 상황을 떠올려요.').replace(/^힌트:\s*/, '');
  if (sl.kind === 'pick') { d.options = sl.opts.map((t, i) => (i === sl.ci ? { text: t, correct: true } : { text: t })); d.note = '풀이: ' + hint + ' → **' + nm(sl.opts[sl.ci]) + '**'; }
  else if (sl.kind === 'collect') { const ch = (keep || sl.chips.map((_, i) => i)).map(i => sl.chips[i]); d.options = ch.map(c => (c.hit ? { text: c.t, correct: true } : { text: c.t })); d.multi = true; d.note = '풀이: ' + hint + ' → 알맞은 것 **' + ch.filter(c => c.hit).length + '개**'; }
  else if (sl.kind === 'match') { d.answer = sl.pairs.map(p => p[0] + ' ↔ ' + p[1]).join(' / '); d.note = '풀이: ' + hint; }
  return d;
}

