function guard(where, s) { const t = String(s), i = t.indexOf('결'); if (i >= 0) throw new Error(where + ' 「결」 글자: ' + t.slice(Math.max(0, i - 30), i + 10)); if (/[『』]/.test(t)) throw new Error(where + ' 겹낫표: ' + t.slice(0, 60)); return t; }

