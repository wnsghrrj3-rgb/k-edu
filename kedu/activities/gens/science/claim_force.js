  var ORDER = ['l01', 'l02', 'l03', 'l04', 'l05', 'l06', 'l07', 'l09'];

  function shuffle(rng, a) {
    a = a.slice();
    for (var i = a.length - 1; i > 0; i--) { var j = Math.floor(rng() * (i + 1)); var t = a[i]; a[i] = a[j]; a[j] = t; }
    return a;
  }

  function item(row, k, rng) {
    var reasons = shuffle(rng, [{ label: row[6], ok: true }, { label: row[7], ok: false }, { label: row[8], ok: false }]);
    return { id: 'cf' + k, l: row[0], type: row[1], who: row[2][0], face: row[2][1], scene: row[3], say: row[4],
             judge: row[5], answer: row[5], reasons: reasons, explain: row[9], prompt: row[4] };
  }

