def _laurel(side):
    """월계수 한 가지 (side=-1 왼쪽, +1 오른쪽) — 왼쪽 추적값, 오른쪽은 좌우 대칭(사진의 원근 기울기 제거)"""
    if side < 0: return [list(poly) for poly in _LAUREL_LEFT]
    return [[(-u, v) for u, v in poly][::-1] for poly in _LAUREL_LEFT]

def _door(x0, x1, y0, y1, arch=0.11, n=12):
    """문 한 짝 — 세로 곧게 오르다 위가 둥근 아치"""
    cx, hw = (x0 + x1) / 2, (x1 - x0) / 2
    pts = [(x0, y0), (x1, y0), (x1, y1 - arch)]
    for i in range(1, n):
        a = math.pi * i / n
        pts.append((cx + hw * math.cos(a), y1 - arch + arch * math.sin(a)))
    pts.append((x0, y1 - arch))
    return pts

# ---------------------------------------------------------------- 메시 만들기
def _mesh_from_polys(name, polys, z0, z1, size, mats, bevel):
    """polys: 2D 다각형 목록 → n각형 면(z1)을 뒤(z0)로 밀어 두께를 내고, 각진 모서리만 bmesh 베벨(금 재질) 후 삼각분할.
    (베벨 모디파이어 + 오목 n각형은 렌더 때 삼각형이 뒤집혀 검은 띠가 생김 — R146. 여기서 직접 나누어 고정)"""
    me = bpy.data.meshes.new(name); o = bpy.data.objects.new(name, me)
    bpy.context.scene.collection.objects.link(o)
    bm = bmesh.new()
    tops = []
    for poly in polys:
        verts = [bm.verts.new((x * size, y * size, z1 * size)) for x, y in poly]
        tops.append(bm.faces.new(verts))
    bmesh.ops.remove_doubles(bm, verts=bm.verts, dist=1e-6 * size)     # 고리 조각처럼 맞닿은 면은 한 덩어리로
    ngons = [f for f in bm.faces if len(f.verts) > 4]
    if ngons: bmesh.ops.triangulate(bm, faces=ngons, ngon_method='EAR_CLIP')    # 오목 다각형은 베벨 전에 미리 귀자르기
    tops = [f for f in bm.faces]
    ext = bmesh.ops.extrude_face_region(bm, geom=tops)
    bmesh.ops.translate(bm, verts=[e for e in ext['geom'] if isinstance(e, bmesh.types.BMVert)], vec=(0, 0, (z0 - z1) * size))
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    if bevel > 0:
        sharp = [e for e in bm.edges if len(e.link_faces) == 2 and e.calc_face_angle(0) > math.radians(40)]
        bmesh.ops.bevel(bm, geom=sharp, offset=bevel * size, offset_type='OFFSET', segments=3, profile=0.5,
                        affect='EDGES', clamp_overlap=True, loop_slide=True, material=1 if len(mats) > 1 else -1)
    ngons = [f for f in bm.faces if len(f.verts) > 4]
    if ngons: bmesh.ops.triangulate(bm, faces=ngons, ngon_method='EAR_CLIP')
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    bm.to_mesh(me); bm.free()
    for m in mats: me.materials.append(m)
    return o

def build(name='emblem', size=1.0, depth=0.12, navy=(0.010, 0.022, 0.111), gold=True, bevel=0.016):
    """엠블럼 부모(빈 객체) 반환. 자식: ring · tip · g(ㄱ) · s(ㅅ) · laurel · door"""
    root = bpy.data.objects.new(name, None); bpy.context.scene.collection.objects.link(root)
    mats = [mat_navy(navy)] + ([mat_gold()] if gold else [])
    d = depth / 0.12                                            # 층 두께는 depth 에 비례
    parts = [
        ('ring',   _ring(),                              0.00 * d, 0.10 * d),
        ('tip',    [_tip()],                             0.00 * d, 0.10 * d),
        ('laurel', _laurel(-1) + _laurel(1),             0.00 * d, 0.08 * d),
        ('door',   [_door(-0.345, -0.055, -1.43, -1.09), _door(0.055, 0.345, -1.43, -1.09)], 0.04 * d, 0.14 * d),
        ('g',      [_wings()[0]],                        0.06 * d, 0.20 * d),
        ('s',      [_wings()[1]],                        0.064 * d, 0.204 * d),   # ㅅ 을 0.004 앞으로 — 겹치는 쐐기의 면 싸움 방지
    ]
    for pname, polys, z0, z1 in parts:
        o = _mesh_from_polys(f'{name}_{pname}', polys, z0, z1, size, mats, (bevel * (0.6 if pname == 'laurel' else 1.0)) if gold else 0.0)   # 잎은 작아서 금선도 가늘게
        o.parent = root
        _smooth(o)
    return root

def _smooth(o):
    """각진 모서리는 살리고 곡면(고리·잎·아치·베벨)만 부드럽게 — 4.1+ 각도 스무딩, 없으면 평면 그대로"""
    try:
        bpy.ops.object.select_all(action='DESELECT'); o.select_set(True); bpy.context.view_layer.objects.active = o
        bpy.ops.object.shade_smooth_by_angle(angle=math.radians(35))
        o.select_set(False)
    except Exception:
        pass

def children(root):
    return [o for o in bpy.context.scene.objects if o.parent == root]
