def _tip():
    """원 꼭대기 창끝 — 밑변이 원 바깥선에 얹히고 옆선이 살짝 오목"""
    return [(-0.24, 0.93), (-0.105, 1.08), (0.0, 1.23), (0.105, 1.08), (0.24, 0.93)]

def _ring(r_out=1.0, r_in=0.89, seg=96):
    """고리 = 사각 조각 seg 개 (구멍 있는 다각형을 피함). 선 굵기 0.11"""
    quads = []
    for i in range(seg):
        a0, a1 = 2 * math.pi * i / seg, 2 * math.pi * (i + 1) / seg
        quads.append([(r_in * math.cos(a0), r_in * math.sin(a0)), (r_out * math.cos(a0), r_out * math.sin(a0)),
                      (r_out * math.cos(a1), r_out * math.sin(a1)), (r_in * math.cos(a1), r_in * math.sin(a1))])
    return quads

