# ---------------------------------------------------------------- 재질
def _principled(name, rgb, rough, metal, coat=0.0):
    m = bpy.data.materials.get(name)
    if m: return m
    m = bpy.data.materials.new(name); m.use_nodes = True
    p = m.node_tree.nodes['Principled BSDF']
    p.inputs['Base Color'].default_value = (*rgb, 1)
    p.inputs['Roughness'].default_value = rough
    p.inputs['Metallic'].default_value = metal
    if 'Coat Weight' in p.inputs: p.inputs['Coat Weight'].default_value = coat
    return m

def mat_navy(rgb=(0.010, 0.022, 0.111)):          # #1c2a5e (선형)
    return _principled('emblem_navy', rgb, 0.28, 0.25, coat=0.8)
def mat_gold():
    return _principled('emblem_gold', (1.0, 0.72, 0.30), 0.22, 1.0)

